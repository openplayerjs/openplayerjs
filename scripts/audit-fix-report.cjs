#!/usr/bin/env node
'use strict';
/**
 * scripts/audit-fix-report.cjs
 *
 * Renders the JSON summary written by scripts/audit-fix.cjs (AUDIT_FIX_SUMMARY_PATH)
 * into either a git commit message or a PR comment body. Kept separate from
 * audit-fix.cjs so the fix logic and its CI presentation don't share one file, and so
 * both the commit message and the PR comment stay in sync with a single data source.
 *
 * Usage:
 *   node scripts/audit-fix-report.cjs --format=commit  <summary.json>
 *   node scripts/audit-fix-report.cjs --format=comment <summary.json>
 *
 * Prints to stdout. Exit code is always 0 (rendering never fails the job); the caller
 * decides what to do with an empty/absent summary.
 */

const { readFileSync, existsSync } = require('fs');

const args = process.argv.slice(2);
const formatArg = args.find(a => a.startsWith('--format='));
const format = formatArg ? formatArg.slice('--format='.length) : null;
const summaryPath = args.find(a => !a.startsWith('--'));

if (!format || !['commit', 'comment'].includes(format) || !summaryPath) {
  process.stderr.write('Usage: node scripts/audit-fix-report.cjs --format=commit|comment <summary.json>\n');
  process.exit(2);
}

if (!existsSync(summaryPath)) {
  process.stderr.write(`No summary file at ${summaryPath}\n`);
  process.exit(0);
}

const summary = JSON.parse(readFileSync(summaryPath, 'utf8'));
const fixed = summary.fixed || [];
const skipped = summary.skipped || [];

function advisoryLine(entry) {
  const from = entry.from ? `${entry.from} → ` : '';
  return `${entry.pkgName} ${from}${entry.to || ''} (${entry.url || `advisory ${entry.id}`})`;
}

if (format === 'commit') {
  if (fixed.length === 0) {
    process.exit(0); // caller should not commit when nothing was fixed
  }
  const lines = ['chore(deps): auto-resolve dependency-audit findings', ''];
  for (const f of fixed) lines.push(`- ${advisoryLine(f)}`);
  lines.push(
    '',
    'Applied by scripts/audit-fix.cjs via the audit-fix job in',
    '.github/workflows/dependency-audit.yml. This only fixes this workspace\'s own',
    'pnpm audit — if a finding\'s dependency path traverses a published package\'s own',
    '"dependencies" (not devDependencies), that package\'s package.json needs a manual',
    'version bump too (run `pnpm why <pkg>` to check); overrides don\'t reach downstream',
    'consumers of that package.',
  );
  if (skipped.length > 0) {
    lines.push('', `${skipped.length} advisor${skipped.length === 1 ? 'y' : 'ies'} could not be auto-fixed and still need manual review:`);
    for (const s of skipped) lines.push(`- ${s.pkgName}: ${s.reason}`);
  }
  process.stdout.write(lines.join('\n') + '\n');
  process.exit(0);
}

// format === 'comment'
if (fixed.length === 0 && skipped.length === 0) {
  process.exit(0); // caller should not post/update a comment when there's nothing to say
}

const lines = ['<!-- audit-fix-bot -->', '### 🔒 Dependency audit auto-fix', ''];
if (fixed.length > 0) {
  lines.push('Pushed a commit resolving these findings via `pnpm-workspace.yaml` overrides:', '');
  for (const f of fixed) lines.push(`- ✅ ${advisoryLine(f)}`);
  lines.push('');
}
if (skipped.length > 0) {
  lines.push('These need a human to resolve — an automatic override can\'t fully fix them:', '');
  for (const s of skipped) lines.push(`- ⚠️ **${s.pkgName}** (${s.url || `advisory ${s.id}`}): ${s.reason}`);
  lines.push('');
}
lines.push('_Generated by scripts/audit-fix.cjs — see the `audit-fix` skill for the manual procedure._');

process.stdout.write(lines.join('\n') + '\n');
process.exit(0);
